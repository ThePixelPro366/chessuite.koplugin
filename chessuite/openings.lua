--[[
Opening book: is a position a known opening position, and what is it called?
Data: chessuite/openings_data.lua, generated by tools/build-openings.lua from
the lichess chess-openings list (CC0, about 3,900 named lines).
--]]

local bit = require("bit")

local Openings = {}

-- 32-bit FNV-1a hash of a position key (see Chess:positionKey()).
function Openings.hash(s)
    local h = 2166136261
    for i = 1, #s do
        h = bit.bxor(h, s:byte(i))
        h = bit.tobit(h * 16777619)
    end
    return bit.band(h, 0x7fffffff)
end

local data
local function load()
    if not data then
        -- loaded from next to this file: KOReader no longer has the plugin
        -- folder on package.path when this first runs
        local dir = debug.getinfo(1, "S").source:match("^@(.*/)") or "./chessuite/"
        local ok, d = pcall(dofile, dir .. "openings_data.lua")
        data = ok and d or { names = {}, book = {} }
    end
    return data
end

-- Name of the opening if this exact position has one.
function Openings.name(game)
    return load().names[Openings.hash(game:positionKey())]
end

function Openings.isBook(game)
    local h = Openings.hash(game:positionKey())
    local d = load()
    return d.names[h] ~= nil or d.book[h] ~= nil
end

-- The most specific opening name reached so far in the game.
function Openings.current(game)
    local Chess = require("chessuite/chess")
    local replay = Chess.new(game.start_fen)
    local name = Openings.name(replay)
    for _, u in ipairs(game:uciHistory()) do
        replay:move(u)
        name = Openings.name(replay) or name
    end
    return name
end

return Openings
