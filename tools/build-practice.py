#!/usr/bin/env python3
"""Builds chessuite/practice_data.lua from the Lichess mobile app's practice
asset (https://github.com/lichess-org/mobile, assets/practice.json, GPL-3.0),
which holds every Lichess Practice course with its lessons, goals and texts.

Usage, from the plugin folder:
    git clone --depth 1 https://github.com/lichess-org/mobile /tmp/lichess-mobile
    python3 tools/build-practice.py /tmp/lichess-mobile/assets/practice.json > chessuite/practice_data.lua
"""
import json
import sys


def lua(v, indent=""):
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "") + '"'
    if isinstance(v, list):
        return "{ " + ", ".join(lua(x, indent) for x in v) + " }"
    if isinstance(v, dict):
        inner = indent + " "
        parts = ["%s%s = %s," % (inner, k, lua(x, inner)) for k, x in v.items()]
        return "{\n" + "\n".join(parts) + "\n" + indent + "}"
    raise TypeError(v)


data = json.load(open(sys.argv[1]))
count = sum(len(st["chapters"]) for s in data["sections"] for st in s["studies"])
print("-- Generated by tools/build-practice.py from the Lichess mobile app's assets/practice.json")
print("-- (https://github.com/lichess-org/mobile, GPL-3.0): Lichess Practice, %d lessons. Do not edit." % count)
print("return " + lua(data))
