-- Builds chessuite/openings_data.lua from the lichess chess-openings TSV files
-- (https://github.com/lichess-org/chess-openings, CC0).
-- Usage, from the plugin folder:
--     git clone https://github.com/lichess-org/chess-openings /tmp/openings
--     luajit tools/build-openings.lua /tmp/openings > chessuite/openings_data.lua
package.path = "./?.lua;" .. package.path
local Chess = require("chessuite/chess")
local dir = arg[1] or "openings"

local hash = require("chessuite/openings").hash

local names, book = {}, {}
local count = 0
for _, f in ipairs({ "a", "b", "c", "d", "e" }) do
    local fh = assert(io.open(dir .. "/" .. f .. ".tsv"))
    fh:read("*l") -- header
    for line in fh:lines() do
        local _, name, pgn = line:match("^([^\t]+)\t([^\t]+)\t(.+)$")
        if pgn then
            local g = Chess.fromPgn(pgn)
            if g then
                count = count + 1
                -- every position on the way is a book position
                local replay = Chess.new()
                for _, u in ipairs(g:uciHistory()) do
                    replay:move(u)
                    book[hash(replay:positionKey())] = true
                end
                -- the named position itself; shorter names win for shared positions
                local h = hash(g:positionKey())
                if not names[h] or #name < #names[h] then names[h] = name end
            end
        end
    end
    fh:close()
end

local out = { "-- Generated by tools/build-openings.lua from lichess chess-openings (CC0). Do not edit.",
    "-- " .. count .. " named lines.", "return {", "names = {" }
local keys = {}
for h in pairs(names) do keys[#keys + 1] = h end
table.sort(keys)
for _, h in ipairs(keys) do out[#out + 1] = string.format("[%d]=%q,", h, names[h]) end
out[#out + 1] = "},"
out[#out + 1] = "book = {"
keys = {}
for h in pairs(book) do if not names[h] then keys[#keys + 1] = h end end
table.sort(keys)
local row = {}
for _, h in ipairs(keys) do
    row[#row + 1] = "[" .. h .. "]=1"
    if #row == 12 then out[#out + 1] = table.concat(row, ",") .. ","; row = {} end
end
if #row > 0 then out[#out + 1] = table.concat(row, ",") .. "," end
out[#out + 1] = "},"
out[#out + 1] = "}"
print(table.concat(out, "\n"))
